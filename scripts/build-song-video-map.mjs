const videoMap = Object.fromEntries(
  research.results.map((result) => {
    const override = overrides.get(result.songId);
    const selected = override ?? result.selected;

    if (!selected) {
      throw new Error(`No YouTube video selected for song ${result.songId}`);
    }

    return [
      String(result.songId),
      {
        videoId: selected.id,
        title: selected.title,
        channel: selected.channel,
        channelId: selected.channelId ?? null,
        channelVerified: selected.channelVerified ?? false,
        duration: selected.duration ?? null,
        selectionTier: override
          ? override.selectionTier ?? "curated"
          : selected.channel?.endsWith(" - Topic")
            ? "topic"
            : selected.channelVerified
              ? "verified-channel"
              : "best-match",
      },
    ];
  }),
);

await writeFile(
  new URL("../src/data/songVideos.json", import.meta.url),
  `${JSON.stringify(videoMap, null, 2)}\n`,
);
